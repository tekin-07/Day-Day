"""Verify local design handoff evidence without additional Python packages."""
from hashlib import sha256
from pathlib import Path
import re
import struct
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
FONT_DIR = ROOT / "apps/web/public/fonts"


def luminance(color):
    rgb = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4 for v in rgb]
    return sum(v * w for v, w in zip(linear, [.2126, .7152, .0722]))


def contrast(first, second):
    low, high = sorted([luminance(first), luminance(second)])
    return (high + .05) / (low + .05)


def verify_contrast():
    css = (ROOT / "apps/web/src/theme.css").read_text()
    pattern = r'\[data-theme="(\w+)"\]\[data-appearance="(\w+)"\] \{([^}]+)\}'
    results = {}
    for theme, appearance, body in re.findall(pattern, css):
        colors = dict(re.findall(r"--([\w-]+):\s*(#[\da-fA-F]+)", body))
        pairs = {}
        for background in ["canvas", "surface"]:
            for foreground in ["ink", "muted", "accent", "danger", "detail", "border", "focus"]:
                threshold = 3 if foreground in ["border", "focus"] else 4.5
                ratio = contrast(colors[foreground], colors[background])
                assert ratio >= threshold, (theme, appearance, foreground, background, ratio)
                pairs[f"{foreground}/{background}"] = ratio
        ratio = contrast(colors["on-accent"], colors["accent"])
        assert ratio >= 4.5, (theme, appearance, "on-accent", ratio)
        pairs["on-accent/accent"] = ratio
        results[f"{theme}-{appearance}"] = pairs
    assert len(results) == 6
    header = ["# Calculated contrast evidence", "", "Generated by `python3 docs/design-options/verify.py` from theme.css.",
              "sRGB relative luminance formula; normal text ≥4.5:1, border/focus ≥3:1.",
              "Focus uses a separated outline on canvas/surface; do not put the focus token directly on accent without a gap.",
              "No functional opacity layers or translucent surfaces are part of this palette.", "",
              "| Pair | " + " | ".join(results) + " |", "| --- | " + " | ".join(["---:"] * 6) + " |"]
    for pair in next(iter(results.values())):
        header.append(f"| {pair} | " + " | ".join(f"{v[pair]:.2f}" for v in results.values()) + " |")
    (OUT / "CONTRAST.md").write_text("\n".join(header) + "\n")
    print("PASS: 90 contrast pairs across six resolved themes")


def font_names(data):
    count = struct.unpack_from(">H", data, 4)[0]
    records = [struct.unpack_from(">4sIII", data, 12 + i * 16) for i in range(count)]
    offset = next(record[2] for record in records if record[0] == b"name")
    _, count, start = struct.unpack_from(">HHH", data, offset)
    names = {}
    for i in range(count):
        platform, _, _, key, length, position = struct.unpack_from(">HHHHHH", data, offset + 6 + i * 12)
        if key in [0, 5, 7, 13] and key not in names:
            raw = data[offset + start + position:offset + start + position + length]
            names[key] = raw.decode("utf-16be" if platform in [0, 3] else "latin1")
    return names


def verify_fonts():
    rows = ["# Bundled font evidence", "", "Unmodified local Noto 2.015 files; no download or font conversion.",
            "The embedded font license is SIL OFL 1.1. The OS noto-fonts Apache license file differs; embedded metadata governs this font handoff.",
            "LICENSE.txt includes font copyright/trademark and the OFL text available locally in `/usr/share/licenses/noto-fonts-cjk/LICENSE`.",
            "`fc-query` reads each font's character map; every listed glyph exists in every face.",
            "Verified characters: `ÇĞİÖŞÜçğıöşü0123456789`.", "", "| File | Bytes | SHA-256 |", "| --- | ---: | --- |"]
    total = 0
    for path in sorted(FONT_DIR.glob("*.ttf")):
        data = path.read_bytes()
        names = font_names(data)
        assert "SIL Open Font License" in names[13]
        assert "2.015" in names[5]
        charset = subprocess.check_output(["fc-query", "--format", "%{charset}", str(path)], text=True)
        intervals = [tuple(int(v, 16) for v in item.split("-")) for item in charset.split()]
        assert all(any(r[0] <= ord(c) <= r[-1] for r in intervals) for c in "ÇĞİÖŞÜçğıöşü0123456789")
        rows.append(f"| {path.name} | {len(data)} | `{sha256(data).hexdigest()}` |")
        total += len(data)
    assert len(list(FONT_DIR.glob("*.ttf"))) == 4
    rows.extend(["", f"Total font payload: **{total:,} bytes**. License: { (FONT_DIR / 'LICENSE.txt').stat().st_size:,} bytes.",
                 "No compressed WOFF2 conversion was performed; the existing TTF payload is larger but avoids another tool/dependency.",
                 "Real-device legibility and font fallback behavior require browser/device checks."])
    (OUT / "FONTS.md").write_text("\n".join(rows) + "\n")
    print(f"PASS: four local font faces; Turkish/numeral glyphs, metadata license, {total} bytes")


def verify_references():
    today = sorted(OUT.glob("today-*.svg"))
    assert len(today) == 12
    signatures = {}
    for path in sorted(OUT.glob("*.svg")):
        root = ET.parse(path).getroot()
        assert root.attrib["width"] in ["360", "412"]
        if path in today:
            geometry = re.sub(r' (fill|stroke|font-family)="[^"]+"', "", path.read_text())
            geometry = re.sub(r'<title[^>]*>.*?</title>', "", geometry)
            width = root.attrib["width"]
            if width in signatures:
                assert geometry == signatures[width], path
            signatures[width] = geometry
    assert len(list(OUT.glob("*.svg"))) == 16
    print("PASS: 16 valid SVGs; all six Today theme variants preserve identical geometry per width")


if __name__ == "__main__":
    verify_contrast()
    verify_fonts()
    verify_references()
